def hall(W, H, seed, cls=None):
    m = (cls or Cave)(W, H, 'T', seed, pool='Lock Water', tid=TID)
    m.STAIRS = CK.K.STAIRS_STONE
    return m


def put_if(m, name, x, y):
    L = CK.STAMPS[name]['layers']; w, h = len(L[0][0]), len(L[0])
    if m.free(x, y, w, h, on='.') and not any((xx, yy) in m.keep_clear for xx in range(x, x + w) for yy in range(y, y + h)):
        m.put(name, x, y); return True
    return False


def hang(m, name, x, y):
    """a wall piece (banner) on the face cells, top layer"""
    L = CK.STAMPS[name]['layers']
    for dy in range(len(L[0])):
        for dx in range(len(L[0][0])):
            t = next((L[z][dy][dx] for z in (2, 1, 0) if L[z][dy][dx]), 0)
            if t and m.inb(x + dx, y + dy) and m.cliff[y + dy, x + dx]: m.over.append((2, x + dx, y + dy, t))


def on_faces(m, name, cells, z=2):
    for x, y in cells:
        if m.cliff[y, x]: m.over.append((z, x, y, P1(name)))


def trainer(at, ttype, name, d, intro, after, sight=3):
    return {'type': 'trainer', 'at': list(at), 'sight': sight, 'dir': d, 'sprite': 'trainer_' + ttype,
            'trainer': [ttype, name], 'intro': intro, 'after': after,
            'rules': ['setBattleRule("field", :%s)' % FIELD]}


def write(m, mid, name, extra=None, comment=''):
    head = {'id': mid, 'name': name, 'parent': 170 if mid != 170 else 160, 'bgm': 'Gym', 'field': FIELD,
            'metadata': dict(META), 'tone': TONE, '_file': '%d_tidelock_gym%s.yaml' % (mid, '' if mid == 170 else '_%d' % mid)}
    head.update(extra or {})
    m.write(mid, head, comment='# GENERATED by mapgen/layouts/tidelock.py (map builder 13): Gym 3 after the GYM_PUZZLES trim.\n'
                               '# Edit the layout script (and puzzles/tidelock.py), not this file.\n' + comment)


