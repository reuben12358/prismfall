class Basin(Cave):
    def paint_ground(self):
        super().paint_ground()
        for y in range(self.H):
            for x in range(self.W):
                if self.cls[y, x] == 'm':
                    self.L[0, y, x] = P1('cv_mud%d' % ((x * 5 + y * 3) % 4 if (x + y) % 3 else 0))


