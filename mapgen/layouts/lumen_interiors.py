def room(W, H, p, seed):
    m = Cave(W, H, p, seed, pool='Cave Pool', tid=TID)
    m.STAIRS = LK.STAIRS_LM or LK.K.STAIRS_STONE
    return m


def put_if(m, name, x, y):
    L = STAMPS[name]['layers']; w, h = len(L[0][0]), len(L[0])
    if m.free(x, y, w, h, on='.') and not any((xx, yy) in m.keep_clear for xx in range(x, x + w) for yy in range(y, y + h)):
        m.put(name, x, y); return True
    return False


def on_faces(m, name, cells):
    for x, y in cells:
        if m.cliff[y, x]: m.over.append((2, x, y, P1(name)))


def hang(m, name, x, y):
    L = STAMPS[name]['layers']
    for dy in range(len(L[0])):
        for dx in range(len(L[0][0])):
            t = next((L[z][dy][dx] for z in (2, 1, 0) if L[z][dy][dx]), 0)
            if t and m.inb(x + dx, y + dy) and m.cliff[y + dy, x + dx]: m.over.append((2, x + dx, y + dy, t))


def carpet(m, x0, y0, x1, y1):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            part = ('n' if y == y0 else 's' if y == y1 else '') + ('w' if x == x0 else 'e' if x == x1 else '')
            m.over.append((1, x, y, P1('lm_carpet_' + (part or 'c'))))


def at(e, x, y): e['at'] = [x, y]; return e


def write(m, mid, name, parent, fn, **kw):
    head = {'id': mid, 'name': name, 'parent': parent, '_file': fn, 'metadata': {'MapPosition': [0, 16, 16]}}
    head.update(kw)
    m.write(mid, head, comment='# GENERATED by mapgen/layouts/lumen_interiors.py (map builder 15).  Edit the layout script, not this file.\n')


