def at(e, x, y): e['at'] = [x, y]; return e


def hall(W, H, seed):
    m = Cave(W, H, 'L', seed, pool='Magma', tid=TID)
    m.STAIRS = CK.K.STAIRS_STONE
    return m


def trench(name, x, y, var):
    """a trench tile: empty (a dark pit) / molten (the magma under it shows) / iron (a grate bridge)"""
    return at(ev(name, page([], tile=PIT_T), page([], cond={'var': [var, 1]}),
                 page([], tile=IRON_T, cond={'var': [var, 2]})), x, y)


def mould(name, x, y, sw):
    return at(ev(name, page([], tile=PIT_T), page([], tile=CAST_T, cond={'switch': sw})), x, y)


def crucible(m, name, x, y, cmds):
    m.over.append((2, x, y - 1, BRAZ_TOP))
    return at(ev(name, page(cmds, tile=BRAZ_FOOT)), x, y)


def trainer(at_, ttype, name, d, intro, after, sight=3):
    return {'type': 'trainer', 'at': list(at_), 'sight': sight, 'dir': d, 'sprite': 'trainer_' + ttype,
            'trainer': [ttype, name], 'intro': intro, 'after': after, 'rules': ['setBattleRule("field", :%s)' % FIELD]}


def write(m, mid, name, parent=240):
    head = {'id': mid, 'name': name, 'parent': parent, 'bgm': 'Gym', 'field': FIELD, 'metadata': dict(META), 'tone': TONE,
            '_file': '%d_foundry_gym%s.yaml' % (mid, '' if mid == 250 else '_%d' % mid)}
    m.write(mid, head, comment='# GENERATED by mapgen/layouts/foundry_gym.py: Gym 7, the Foundry (GYM_PUZZLES Gym 7; '
                               'puzzle proofs mapgen/puzzles/foundry.py).\n# Edit the layout script, not this file.\n')


def dress(m, braziers, embers=()):
    for x, y in braziers:
        if m.cls[y, x] == '.' and (x, y) not in m.keep_clear and m.cls[y - 1, x] != '.':
            m.over.append((2, x, y - 1, BRAZ_TOP)); m.over.append((1, x, y, BRAZ_FOOT))
    for i, (x, y) in enumerate(embers):
        if m.cls[y, x] == '.' and (x, y) not in m.keep_clear:
            m.over.append((1, x, y, P1('wr_ember%d' % (i % 3))))


