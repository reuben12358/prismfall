def node_tile(sh, r): return P1('lm_node%s%d' % (sh, r))


def board_events(m, mid, shock=False):
    """every strip, node, socket and lamp of the proven board (puzzles/circuit.py BOARDS[mid])"""
    b = CI.BOARDS[mid]; E = []
    for (x, y), k in sorted(b['cells'].items()):
        if k[0] == 'S':
            kind = 'h' if k[1] == CI.H else 'v'
            lit = page([S('pfm_g4_shock')] if shock else [], tile=P1('lm_strip_%s_on' % kind), cond={'self': 'A'},
                       trigger='touch' if shock else 'action')
            E.append(dict(ev('Strip %d,%d' % (x, y), page([], tile=P1('lm_strip_' + kind)), lit), at=[x, y]))
        elif k[0] == 'N' and k[3]:
            n = CI.NROT[k[1]]; pages = []
            for s in range(n):
                cond = {'self': 'ABC'[s - 1]} if s else None
                pages.append(page([S('pfm_g4_turn("Node %d,%d", %d)' % (x, y, n))], tile=node_tile(k[1], (k[2] + s) % n), cond=cond))
            E.append(dict(ev('Node %d,%d' % (x, y), *pages), at=[x, y]))
        elif k[0] == 'N':
            m.over.append((1, x, y, node_tile(k[1], k[2])))
            E.append(dict(ev('Welded %d,%d' % (x, y), page(["The junction is soldered in place. A label in Rook's handwriting: DON'T."])), at=[x, y]))
        elif k[0] == 'B':
            E.append(dict(ev('Socket', page([S('pfm_g4_socket')], tile=P1('lm_socket')),
                             page([S('pfm_g4_socket')], tile=P1('lm_socket_drone'), cond={'switch': CI.S_DOCKED})), at=[x, y]))
    (sx, sy), _ = b['source']
    m.put('lm_gen', sx - 1, sy - 1)
    pre = [S('$game_switches[%d] = false' % CI.S_DOCKED)] if mid == 192 else []
    E.append(dict(ev('Power', page(pre + [S('pfm_g4_power(%d)' % mid), {'raw': [116, []]}], trigger='autorun')), at=[0, 0]))
    for (x, y), k in b['cells'].items():
        m.keep_clear.add((x, y))
        if k[0] == 'L' and k[1] not in ('door191', 'latch1', 'latch2', 'alarm'):
            pass
    return E


def dress_studio(m, props, seed=0):
    for name, x, y in props: put_if(m, name, x, y)


def clean_studio_floor(m):
    """Strip noisy random cyan Z_f3 blotches so dark-glass studio tiles & circuit boards read razor-sharp."""
    z_f0, z_f2, z_f3 = P1('Z_f0'), P1('Z_f2'), P1('Z_f3')
    for y in range(m.H):
        for x in range(m.W):
            if m.L[0, y, x] == z_f3:
                m.L[0, y, x] = z_f2 if ((x + y) & 1) else z_f0


def put_carpet(m, x0, y0, x1, y1):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            part = ('n' if y == y0 else 's' if y == y1 else '') + ('w' if x == x0 else 'e' if x == x1 else '')
            m.L[0, y, x] = P1('lm_carpet_' + (part or 'c'))


def abyss_piece(m, name, x, y):
    st = STAMPS[name]; h, w = st['h'], st['w']
    for dy in range(h):
        for dx in range(w):
            for z in (1, 2):
                t = st['layers'][z][dy][dx]
                if t and m.inb(x + dx, y + dy):
                    m.over.append((z, x + dx, y + dy, t))


def paint_deeps(m):
    deeps = [P1('lm_deep%d' % i) for i in range(6)]
    for y in range(m.H):
        for x in range(m.W):
            if m.cls[y, x] == 'p':
                m.L[0, y, x] = deeps[(x * 7 + y * 13) % len(deeps)]


