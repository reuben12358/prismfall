#!/usr/bin/env python3
"""Writes specs/990_test_arena.yaml: one NPC per field in SPINE's roster (+ a healer). Re-run after roster changes."""
import os
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
FIELDS = [  # (field id, display name, wild species for the test battle)
    ('SILKWOOD', 'Silkwood', 'SPINARAK'), ('GRAND_STAGE', 'Grand Stage', 'LILLIPUP'),
    ('WATER_SURFACE', 'Water Surface', 'MARILL'), ('NEON_GRID', 'Neon Grid', 'ELEKID'),
    ('DESERT', 'Desert', 'SANDSHREW'), ('CORROSIVE_MIRE', 'Corrosive Mire', 'GRIMER'),
    ('VOLCANIC', 'Volcanic', 'SLUGMA'), ('COLOSSEUM', 'Colosseum', 'MACHOP'),
    ('FLOWER_GARDEN', 'Flower Garden', 'BUDEW'), ('FROZEN_LAKE', 'Frozen Lake', 'SNORUNT'),
    ('STORMFRONT', 'Stormfront', 'STARLY'), ('MINDSCAPE', 'Mindscape', 'RALTS'),
    ('CRYSTAL_CAVERN', 'Crystal Cavern', 'CARBINK'), ('HOLLOW_CATHEDRAL', 'Hollow Cathedral', 'GASTLY'),
    ('FACTORY', 'Factory', 'MAGNEMITE'), ('NEW_MOON', 'New Moon', 'MURKROW'),
    ('FAIRY_TALE', 'Fairy Tale', 'FLABEBE'), ('DRAGONS_DEN', "Dragon's Den", 'DRATINI'),
    ('CAVE', 'Cave', 'ZUBAT'), ('MOUNTAIN', 'Mountain', 'GEODUDE'), ('SNOWY_MOUNTAIN', 'Snowy Mountain', 'SWINUB'),
    ('BEACH', 'Beach', 'WINGULL'), ('UNDERWATER', 'Underwater', 'CHINCHOU'), ('RAINBOW', 'Rainbow', 'SWABLU'),
    ('WASTELAND', 'Wasteland', 'TRUBBISH'), ('ASHEN_WASTE', 'Ashen Waste', 'NUMEL'),
    ('DARK_CRYSTAL', 'Dark Crystal', 'SABLEYE'), ('SCRAPYARD', 'Scrapyard', 'KLINK'),
    ('INVERSE', 'Inverse', 'INKAY'), ('BLEED', 'Bleed', 'PORYGON'), ('PRISM_ARENA', 'Prism Arena', 'EEVEE'),
    ('WILDFIRE', 'Wildfire', 'GROWLITHE'), ('MEADOW', 'Meadow', 'DEERLING')]
SPRITES = ['trainer_YOUNGSTER', 'trainer_LASS', 'trainer_BUGCATCHER', 'trainer_PICNICKER', 'trainer_HIKER',
           'trainer_SWIMMER_F', 'trainer_SCIENTIST', 'trainer_BLACKBELT', 'trainer_AROMALADY', 'trainer_POKEMANIAC',
           'trainer_BIRDKEEPER', 'trainer_PSYCHIC_F', 'trainer_RUINMANIAC', 'trainer_CHANNELER', 'trainer_ENGINEER',
           'trainer_BURGLAR', 'trainer_LADY', 'trainer_COOLTRAINER_M']
# free floor cells of the stretched arena (21x13): NPC rows y=2/4/6/8, columns left of the left pillars (x=6) and right
# of the right pillars (x=14); rows 3/5/7/9 stay free (linked through the centre) so every NPC is reachable.
SLOTS = [(x, y) for y in (2, 4, 6, 8) for x in list(range(1, 6)) + list(range(15, 20))]


def npc(i, fid, name, species):
    x, y = SLOTS[i]
    rules = 'setBattleRule("field", :%s)\nsetBattleRule("canLose")' % fid
    return {'type': 'npc', 'name': 'Field %s' % fid, 'at': [x, y], 'sprite': SPRITES[i % len(SPRITES)],
            'dir': 'down', 'commands': [
                'Test field: %s (:%s).' % (name, fid),
                {'choices': ['Wild battle', 'Trainer battle', 'Cancel'], 'cancel': 3, 'branches': [
                    [{'script': rules + '\nWildBattle.start(:%s, 20)\n$player.heal_party' % species}],
                    [{'script': rules + '\nTrainerBattle.start(:YOUNGSTER, "Prismtest")\n$player.heal_party'}],
                    []]}]}


def main():
    assert len(FIELDS) <= len(SLOTS) - 1
    events = [npc(i, *f) for i, f in enumerate(FIELDS)]
    hx, hy = SLOTS[len(FIELDS)]
    events.append({'type': 'npc', 'name': 'Healer', 'at': [hx, hy], 'sprite': 'NPC 16', 'dir': 'down',
                   'commands': ['Let me heal your team.', {'heal': True}, {'me': 'Pkmn healing'}, {'wait': 40},
                                'All better! (Battles here use setBattleRule("canLose").)']})
    events.append({'type': 'warp', 'name': 'Exit', 'at': [10, 12], 'to': {'map': 100, 'x': 24, 'y': 28, 'dir': 'down'},
                   'se': 'Door exit'})
    events.append({'type': 'sign', 'name': 'Arena sign', 'at': [10, 3], 'post': False, 'text':
                   'PRISMFALL TEST ARENA - talk to a trainer to start a battle on their field. '
                   'Reach this room via Debug > Warp to map 990.'})
    raw_990 = os.path.join(HERE, 'data', 'raw', '990.npy')
    if os.path.exists(raw_990):
        spec = {'id': 990, 'name': 'Prismfall Test Arena', 'parent': 0, 'tileset': 34, 'raw': 'data/raw/990.npy',
                'tone': [4, 2, 6, 0], 'bgm': 'Battle Frontier', 'metadata': {'Name': 'Test Arena'}, 'events': events}
    else:
        spec = {'id': 990, 'name': 'Prismfall Test Arena', 'parent': 0, 'template': 'arena',
                'stretch': [['x', 1, 4], ['x', 15, 4]], 'drop_template_events': ['Champion', 'Door', 'Entrance'],
                'bgm': 'Battle Frontier', 'metadata': {'Name': 'Test Arena'}, 'events': events}
    with open(os.path.join(HERE, 'specs', '990_test_arena.yaml'), 'w') as f:
        f.write('# GENERATED by gen_test_arena.py (layout crafted by wave16_final12_craft.py).\n')
        yaml.safe_dump(spec, f, sort_keys=False, allow_unicode=True, width=120)
    print('wrote specs/990_test_arena.yaml with', len(events), 'events')


if __name__ == '__main__':
    main()
