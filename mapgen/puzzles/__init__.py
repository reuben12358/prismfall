"""mapgen/puzzles - solver models for every built puzzle room, and the runtime room registry they share with the
engine (GYM_PUZZLES section 4 item 10).  build.py calls run_all() and (with --strict) fails the build when a room is
unsolvable, can soft-lock, or its shortest solution is not the designed one.

    python3 -I mapgen/puzzle_check.py     # print every proof"""
import importlib

MODULES = ['loomhouse', 'canopy', 'playhouse', 'dungeons', 'tidelock', 'manor', 'circuit', 'foundry', 'infirmary']


def modules():
    out = []
    for n in MODULES:
        try:
            out.append(importlib.import_module('.' + n, __name__))
        except ModuleNotFoundError as e:
            if e.name != __name__ + '.' + n: raise
    return out


def run_all(verbose=True):
    from .core import verify
    bad = 0; lines = []
    for mod in modules():
        for make, kw in mod.CHECKS:
            ok, out = verify(make(), **kw) if callable(make) else make(**kw)
            lines += out; bad += 0 if ok else 1
        for fn in getattr(mod, 'EXTRA', []):
            ok, out = fn(); lines += out; bad += 0 if ok else 1
    if verbose:
        for l in lines: print('PUZZLE', l)
    return bad, lines


def run_built(verbose=True):
    """Engine-level proofs on maps_out/Data (see built.py)."""
    from . import built
    bad, lines = built.run(modules())
    if verbose:
        for l in lines: print('PUZZLE', l)
    return bad, lines


def rb(v, ind=0):
    """Python literal -> Ruby literal (dict keys: int stay ints, str become strings; top-level names use symbols)."""
    if isinstance(v, bool): return 'true' if v else 'false'
    if v is None: return 'nil'
    if isinstance(v, (int, float)): return repr(v)
    if isinstance(v, str): return '"' + v.replace('\\', '\\\\').replace('"', '\\"') + '"'
    if isinstance(v, (list, tuple)): return '[' + ', '.join(rb(x) for x in v) + ']'
    if isinstance(v, dict):
        return '{ ' + ', '.join('%s => %s' % (rb(k) if not isinstance(k, tuple) else rb(list(k)), rb(x)) for k, x in v.items()) + ' }'
    raise TypeError(v)


def ruby_registry():
    L = ['# GENERATED by mapgen/puzzles (the same data the solver proves) - do not edit.',
         '# Rooms: reset / solved state, start tile and tiered hints for pfp_apprentice, pfp_reset, pfp_hint.',
         'if defined?(PrismfallPuzzles)']
    for mod in modules():
        for rid, r in mod.ROOMS.items():
            L.append('  PrismfallPuzzles.room(:%s, {' % rid)
            for k, v in r.items():
                if isinstance(v, dict):
                    L.append('    :%s => { %s },' % (k, ', '.join(':%s => %s' % (kk, rb(vv)) for kk, vv in v.items())))
                else:
                    L.append('    :%s => %s,' % (k, rb(v)))
            L.append('  })')
        L += ['  ' + l for l in getattr(mod, 'RUBY', '').strip('\n').split('\n') if l]
    L.append('end')
    return '\n'.join(L) + '\n'
