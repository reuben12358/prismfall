# What a player can have caught by each badge count, for the win-rate harness (round 4).
#   python3 -I tools/trainer_gen/pools.py > tools/harness/winrate_pools.json
# For every badge count b (0-18): each wild species' best encounter rate (%) on any table the player can use while
# holding b badges: maps.json `segment` <= b, the method unlocked (validate_encounters.UNLOCK: Good Rod 3, Rock
# Smash 2, Surf 6, Super Rod 10), plus every badge-tier overlay [map, 100 + t] with t <= b (BADGE_TIERS.md).
# Headbutt, Rock Smash and rod rates count x0.3 (a few trees, rocks and casts per map), as round 3's pools did; Surf x0.6
# (a player walks more grass than water).
# Output: {species: [[b, rate], ...]}, one pair each time the species' best rate changes (first pair = first badge count).
# Gifts, quest and event Pokemon are not encounters: run_winrates.rb adds them by badge count (EVENT_LATE).
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import validate_encounters as V

SLOW = ("Headbutt", "RockSmash", "OldRod", "GoodRod", "SuperRod")


def main():
    et = V.parse_enc_types("/home/claude/ref/essentials/Data/Scripts")
    base = V.parse_encounters(os.path.join(ROOT, "pbs", "encounters.txt"), et, [])
    tiers = V.parse_encounters(os.path.join(ROOT, "pbs", "encounters_badgetiers.txt"), et, [])
    info = {m["id"]: m for m in json.load(open(os.path.join(ROOT, "design", "maps.json")))["maps"]}

    def seg(mid):
        s = info.get(mid, {}).get("segment")
        return V.segment_from_id(mid) if s is None else s

    out = {}
    for b in range(19):
        best = {}
        def take(table_types, extra_total=None):
            for t, slots in table_types.items():
                if V.base_unlock(t) > b:
                    continue
                tot = extra_total.get(t) if extra_total else None
                tot = tot or sum(s[0] for s in slots) or 1
                mult = 0.3 if t.startswith(SLOW) else 0.6 if t.startswith("Water") else 1.0
                for (w, sp, lo, hi, no) in slots:
                    r = round(100.0 * w / tot * mult, 1)
                    if r > best.get(sp, 0):
                        best[sp] = r
        totals = {}
        for (mid, ver), m in base.items():
            if ver != 0 or seg(mid) > b:
                continue
            totals[mid] = {t: sum(s[0] for s in sl) for t, sl in m["types"].items()}
            take(m["types"])
        for (mid, ver), m in tiers.items():
            t = ver - 100
            if not (0 < t <= b) or mid not in totals:
                continue
            # an overlay's weight counts against the base table it joins (Land overlays also feed LandDay/Night)
            tot = {}
            for et_name in m["types"]:
                cands = [v for k, v in totals[mid].items() if k == et_name or k.startswith(et_name)]
                tot[et_name] = (max(cands) if cands else 0) + sum(s[0] for s in m["types"][et_name])
            take(m["types"], tot)
        out[b] = best
    sp = {}
    for b in range(19):
        for s_, r in out[b].items():
            h = sp.setdefault(s_, [])
            if not h or h[-1][1] != r:
                h.append([b, r])
    sys.stdout.write('{"about": "best wild rate (%%) by badges held, [[badges, rate], ...]; generated by tools/trainer_gen/pools.py",\n')
    sys.stdout.write(' "species": {\n')
    sys.stdout.write(",\n".join("  %s: %s" % (json.dumps(k), json.dumps(v, separators=(",", ":"))) for k, v in sorted(sp.items())))
    sys.stdout.write("\n }\n}\n")


if __name__ == "__main__":
    main()
